def add_footer(canvas, doc):
    canvas.saveState()

    width, height = A4

    canvas.setFont("Helvetica", 8)
    canvas.setFillColor(colors.grey)

    footer_text = "Generated by Agentic Data Parsing Engine"
    page_text = f"Page {doc.page}"

    canvas.drawString(inch, 0.45 * inch, footer_text)
    canvas.drawRightString(width - inch, 0.45 * inch, page_text)

    canvas.restoreState()


def markdown_line_to_flowable(line: str, styles):
    line = line.strip()

    if not line:
        return Spacer(1, 8)

    if line == "---":
        return Spacer(1, 14)

    if line.startswith("# "):
        text = clean_text(line.replace("# ", "", 1))
        return Paragraph(text, styles["ReportTitle"])

    if line.startswith("## "):
        text = clean_text(line.replace("## ", "", 1))
        return Paragraph(text, styles["SectionHeading"])

    if line.startswith("### "):
        text = clean_text(line.replace("### ", "", 1))
        return Paragraph(text, styles["SubHeading"])

    if line.startswith("- "):
        text = clean_text(line.replace("- ", "", 1))
        return Paragraph(text, styles["BulletTextCustom"], bulletText="•")

    if line.startswith("```"):
        return Spacer(1, 4)

    if line.startswith("`") and line.endswith("`"):
        text = clean_text(line.replace("`", ""))
        return Paragraph(text, styles["CodeText"])

    # Basic markdown cleanup
    line = line.replace("**", "")
    line = line.replace("`", "")

    return Paragraph(clean_text(line), styles["BodyTextCustom"])


def generate_pdf_from_markdown(markdown_path, pdf_path=None):
    markdown_path = Path(markdown_path)

    if not markdown_path.exists():
        raise FileNotFoundError(f"Markdown report not found: {markdown_path}")

    if pdf_path is None:
        pdf_path = markdown_path.with_suffix(".pdf")

    pdf_path = Path(pdf_path)
    pdf_path.parent.mkdir(parents=True, exist_ok=True)

    with open(markdown_path, "r", encoding="utf-8") as file:
        markdown_content = file.read()

    styles = get_pdf_styles()

    doc = SimpleDocTemplate(
        str(pdf_path),
        pagesize=A4,
        rightMargin=0.75 * inch,
        leftMargin=0.75 * inch,
        topMargin=0.75 * inch,
        bottomMargin=0.75 * inch,
        title="Agentic Diagnostic Report",
        author="Agentic Data Parsing Engine",
    )

    story = []

    for line in markdown_content.splitlines():
        flowable = markdown_line_to_flowable(line, styles)
        story.append(flowable)

    doc.build(
        story,
        onFirstPage=add_footer,
        onLaterPages=add_footer,
    )

    return pdf_path