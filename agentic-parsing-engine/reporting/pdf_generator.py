def clean_text(text: str) -> str:
    """
    ReportLab Paragraph uses XML-like markup.
    So we escape special characters safely.
    """
    return (
        str(text)
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
    )


